export type SupportedCity = keyof typeof locationCatalog;

export const supportedCities = Object.keys(locationCatalog) as SupportedCity[];

export function districtsForCity(city?: string) {
  return city && city in locationCatalog ? locationCatalog[city as SupportedCity] : [];
}

export function isSupportedDistrict(city: string | undefined, district: string | undefined) {
  return !district || districtsForCity(city).includes(district as never);
}
